"""지역 감지 유틸리티 — JSON 데이터에서 광역시/도 단위 지역명 반환."""

import re

# "서울24호", "경기7호" 같은 업체명 패턴 → 지역 감지 오염 방지
_COMPANY_NAME_RE = re.compile(
    r'(서울|경기|인천|부산|대구|대전|울산|광주|세종|강원|충북|충남|전북|전남|경북|경남|제주)\d+호'
)

# 순서 중요: 구체적인 패턴 → 넓은 패턴 순
# 경기도 광주시와 광주광역시 혼동 방지를 위해 경기를 먼저 처리
REGION_PATTERNS = [
    ("서울", ["서울특별시", "서울시", "서울"]),
    ("경기", [
        "경기도", "수원시", "성남시", "의정부시", "안양시", "부천시", "광명시",
        "평택시", "시흥시", "군포시", "의왕시", "하남시", "오산시", "용인시",
        "안성시", "김포시", "화성시", "고양시", "과천시", "구리시", "남양주시",
        "파주시", "양주시", "동두천시", "안산시", "이천시", "여주시", "포천시",
        "가평군", "양평군", "연천군", "경기",
    ]),
    ("인천", ["인천광역시", "인천시", "인천"]),
    ("부산", ["부산광역시", "부산시", "부산"]),
    ("대구", ["대구광역시", "대구시", "대구"]),
    ("대전", ["대전광역시", "대전시", "대전"]),
    ("울산", ["울산광역시", "울산시", "울산"]),
    ("세종", ["세종특별자치시", "세종시", "세종"]),
    ("광주", ["광주광역시"]),   # 단독 '광주'는 경기 광주시와 혼동 가능 → 제외
    ("강원", ["강원특별자치도", "강원도", "강원", "춘천시", "원주시", "강릉시",
              "동해시", "태백시", "속초시", "삼척시"]),
    ("충북", ["충청북도", "충북", "청주시", "충주시", "제천시"]),
    ("충남", ["충청남도", "충남", "천안시", "공주시", "아산시", "서산시",
              "보령시", "논산시", "당진시"]),
    ("전북", ["전라북도", "전북특별자치도", "전북", "전주시", "군산시", "익산시",
              "정읍시", "남원시", "김제시"]),
    ("전남", ["전라남도", "전남", "목포시", "여수시", "순천시", "나주시", "광양시"]),
    ("경북", ["경상북도", "경북", "포항시", "경주시", "안동시", "구미시",
              "영주시", "영천시", "상주시"]),
    ("경남", ["경상남도", "경남", "창원시", "진주시", "통영시", "김해시",
              "밀양시", "거제시", "양산시"]),
    ("제주", ["제주특별자치도", "제주도", "제주시", "서귀포시", "제주"]),
]


def detect_region(data: dict) -> str:
    """
    JSON 데이터에서 광역시/도 단위 지역명 반환.

    탐색 전략:
    1. location 필드 단독 탐색 (가장 신뢰도 높음)
    2. location이 없으면 post_title / body_text / request_body_text 탐색
       - 업체명 패턴("서울24호" 등) 제거 후 검색해 오분류 방지
    감지 실패 시 '기타' 반환.
    """
    # 1순위: location 필드 (크롤러가 "공사지역" 줄에서 추출한 값)
    location = data.get("location", "")
    if location:
        for region, keywords in REGION_PATTERNS:
            for kw in keywords:
                if kw in location:
                    return region

    # 2순위: 나머지 텍스트 (업체명 패턴 제거 후 탐색)
    other_texts = [
        data.get("post_title", ""),
        (data.get("body_text") or "")[:500],
        (data.get("request_body_text") or "")[:500],
    ]
    combined = _COMPANY_NAME_RE.sub("", " ".join(t for t in other_texts if t))

    for region, keywords in REGION_PATTERNS:
        for kw in keywords:
            if kw in combined:
                return region

    return "기타"
